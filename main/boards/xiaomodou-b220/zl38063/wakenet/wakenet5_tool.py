#!/usr/bin/env python3
"""WakeNet5 "modoujingling" model image tool.

Input : wakenet5_modoujingling.bin  (84 160 bytes, raw DROM image extracted from the
        stock 小魔豆 B220 firmware, DROM 0x3f4131b0 .. 0x3f427a70)

Layout of that image (all little-endian, all proven byte-for-byte):

  +0x0000  model_coeff_getter_t  (24 bytes, 6 x 32-bit function pointer slots)
              +0x00 getter_f   = NULL
              +0x04 getter_q   = <IROM get_coeff_q>   (name -> dl_matrix2dq_t*)
              +0x08 getter_q8  = NULL
              +0x0c free_f     = NULL
              +0x10 getter_info= <IROM get_info>      (returns model_info_t*)
              +0x14 free_q8    = NULL
  +0x0018  10 x dl_matrix2dq_t (24-byte header) each immediately followed by its
           int16 item array; then 10 x dl_matrix2dq_t bias vectors likewise, back to
           back, ending exactly at +0x148c0.

  dl_matrix2dq_t = { int w; int h; int stride; int flags; int exponent; qtp_t *itemq; }
  (esp-sr managed_components/espressif__esp-sr/include/esp32/dl_lib_matrixq.h:28-35)
  item bytes = w * stride * sizeof(int16_t)

Usage:
  python wakenet5_tool.py info                  # print the object table
  python wakenet5_tool.py emit <outdir> [prefix]  # emit relocatable C source
"""
import struct, hashlib, os, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
BIN = os.path.join(HERE, 'wakenet5_modoujingling.bin')

# recovered from the stock firmware (see README.md)
MODEL_NAME = ('wakeNet5_v3_modoujingling_6_0.90_0.85_'
              'kuaisuqianjin_6_0.90_0.85_tiaogewu_6_0.90_0.85')
WORD_LIST = ['modoujingling', 'kuaisuqianjin', 'tiaogewu']
WIN_LIST = [6, 6, 6]
THRESH_LIST = [0.90, 0.85, 0.90, 0.85, 0.90, 0.85]
NAME_ORDER = (['kernel_%d' % i for i in range(9, -1, -1)] +
              ['bias_%d' % i for i in range(9, -1, -1)])


def parse(path=BIN):
    """Walk the image and return (getter slots, [(name, header, items_bytes), ...])."""
    d = open(path, 'rb').read()
    slots = struct.unpack_from('<6I', d, 0)
    objs = []
    pos = 24
    while pos < len(d):
        w, h, stride, flags, exp, item = struct.unpack_from('<iiiiii', d, pos)
        # itemq is the stock's absolute DROM address of the item array, which always
        # sits immediately after the 24-byte header.
        assert item == 0x3f4131b0 + pos + 24, 'itemq 0x%08x at +0x%x' % (item, pos)
        assert stride == h, 'stride %d != h %d at +0x%x' % (stride, h, pos)
        n = w * stride * 2
        objs.append((dict(w=w, h=h, stride=stride, flags=flags,
                          exponent=exp, item_off=pos + 24), d[pos + 24:pos + 24 + n]))
        pos += 24 + n
    assert pos == len(d), 'trailing bytes: %d' % (len(d) - pos)
    assert len(objs) == 20, len(objs)
    return slots, objs


def info():
    d = open(BIN, 'rb').read()
    print('file   : %s' % BIN)
    print('size   : %d bytes (0x%x)' % (len(d), len(d)))
    print('sha256 : %s' % hashlib.sha256(d).hexdigest())
    slots, objs = parse()
    got = [s for s in slots if s]
    print('\ngetter struct @ +0x0000')
    for i, nm in enumerate(['getter_f', 'getter_q', 'getter_q8',
                            'free_f', 'free_q', 'free_q8']):
        print('  +0x%02x %-11s = 0x%08x%s' % (i * 4, nm, slots[i],
              '   (IROM)' if slots[i] > 0x40000000 else ''))
    print('\nobject table')
    print('  %-10s %-6s %-10s %-4s %-4s %-4s %-6s %-6s %s' %
          ('name', 'offset', 'vma_stock', 'w', 'h', 'str', 'flags', 'exp', 'ints'))
    off = 24
    for name, (h, body) in zip(NAME_ORDER, objs):
        print('  %-10s 0x%05x  0x%08x  %-4d %-4d %-4d %-4d %-6d %d' %
              (name, off, 0x3f4131b0 + off, h['w'], h['h'], h['stride'],
               h['flags'], h['exponent'], len(body) // 2))
        off += 24 + len(body)
    print('\ntotal item bytes: %d' % sum(len(b) for _, b in objs))
    print('model_info_t (stock @0x3f427a70, just past the image):')
    print('  word_num=%d word_list=%s win_list=%s thresh_list=%s' %
          (len(WORD_LIST), WORD_LIST, WIN_LIST, THRESH_LIST))
    print('  info_str="%s"' % MODEL_NAME)


def emit(outdir, prefix='modoujingling_wn5'):
    os.makedirs(outdir, exist_ok=True)
    slots, objs = parse()
    hdr = open(os.path.join(outdir, prefix + '.h'), 'w')
    src = open(os.path.join(outdir, prefix + '.c'), 'w')
    hdr.write('//Generated by wakenet5_tool.py from the stock B220 firmware\n'
              '#pragma once\n#include <string.h>\n'
              '#include "dl_lib_coefgetter_if.h"\n#include "dl_lib_matrix.h"\n'
              '#include "dl_lib_matrixq.h"\n#include "dl_lib_matrixq8.h"\n\n'
              'extern const model_coeff_getter_t get_coeff_%s;\n' % prefix)
    src.write('//Generated by wakenet5_tool.py from the stock B220 firmware\n'
              '#include "%s.h"\n\n' % prefix)
    src.write('static const char *wake_word_list[] = {%s};\n' %
              ', '.join('"%s"' % w for w in WORD_LIST))
    src.write('static int det_win_list[] = {%s};\n' % ', '.join(map(str, WIN_LIST)))
    src.write('static float det_thresh_list[] = {%s};\n' %
              ', '.join('%.2ff' % t for t in THRESH_LIST))
    src.write('static char *info_str = "%s";\n' % MODEL_NAME)
    src.write('static const model_info_t model_info = {%d, (char **)wake_word_list,'
              ' det_win_list, det_thresh_list, info_str};\n\n' % len(WORD_LIST))
    for name, (h, body) in zip(NAME_ORDER, objs):
        sym = name
        src.write('static const qtp_t %s_item[] = {\n' % sym)
        for i in range(0, len(body), 16):
            src.write('    ' + ','.join('%d' % v for v in
                      struct.unpack_from('<%dh' % (len(body[i:i+16]) // 2), body, i)) + ',\n')
        src.write('};\n')
        src.write('static const dl_matrix2dq_t %s = {%d, %d, %d, %d, %d, %s_item};\n\n'
                  % (sym, h['w'], h['h'], h['stride'], h['flags'], h['exponent'], sym))
    src.write('static const dl_matrix2dq_t *get_coeff_q(const char *name, void *arg, int hint)\n{\n')
    for name in NAME_ORDER:
        src.write('    if (strcmp(name, "%s") == 0) return &%s;\n' % (name, name))
    src.write('    return NULL;\n}\n\n')
    src.write('static const model_info_t *get_info(void *arg)\n{\n'
              '    return &model_info;\n}\n\n')
    src.write('// 9-slot layout of dl_lib_coefgetter_if.h as shipped by esp-sr v1.0/v1.9.5.\n'
              '// The stock firmware was built against an earlier 6-slot revision whose\n'
              '// slot 4 held the model-info getter - see ../README.md.\n'
              'const model_coeff_getter_t get_coeff_%s = {\n'
              '    NULL,             // getter_f\n'
              '    get_coeff_q,      // getter_q\n'
              '    NULL,             // getter_q8\n'
              '    NULL,             // free_f\n'
              '    NULL,             // free_q\n'
              '    NULL,             // free_q8\n'
              '    get_info,         // getter_info\n'
              '    NULL,             // getter_alphabet\n'
              '    NULL,             // getter_config\n};\n' % prefix)
    hdr.close()
    src.close()
    print('wrote %s.c and %s.h in %s' % (prefix, prefix, outdir))
    print('plug in with: #define WAKENET_COEFF get_coeff_%s' % prefix)


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'info'
    if cmd == 'info':
        info()
    elif cmd == 'emit':
        emit(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'modoujingling_wn5')
    else:
        print(__doc__)
